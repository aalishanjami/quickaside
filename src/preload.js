'use strict';

const { contextBridge, ipcRenderer } = require('electron');

const CHANNELS = new Set([
  'status',
  'level',
  'transcript:add',
  'transcript:remove',
  'qa:update',
  'panel:minimized',
  'model:progress',
  'models',
  'toast',
  'reset',
  'call:started',
  'call:stopping',
  'focus-input',
  'settings',
  'settings:section',
  'prompt:show',
  'draft:progress',
  'notes:update',
  'calls:changed',
]);

contextBridge.exposeInMainWorld('quickaside', {
  getState: () => ipcRenderer.invoke('state:get'),
  updateSettings: (patch) => ipcRenderer.invoke('settings:update', patch),
  openSettings: (section) => ipcRenderer.invoke('settings:open', section),
  hidePanel: () => ipcRenderer.invoke('panel:hide'),
  minimizePanel: (on) => ipcRenderer.invoke('panel:minimize', on),
  promptStart: () => ipcRenderer.invoke('prompt:start'),
  promptDismiss: () => ipcRenderer.invoke('prompt:dismiss'),
  setNote: (text) => ipcRenderer.invoke('note:set', text),
  draft: (fields, project) => ipcRenderer.invoke('draft:run', { fields, project }),
  cancelDraft: () => ipcRenderer.invoke('draft:cancel'),
  knowledge: () => ipcRenderer.invoke('knowledge:overview'),
  reveal: (file) => ipcRenderer.invoke('shell:reveal', file),
  startCall: () => ipcRenderer.invoke('call:start'),
  stopCall: () => ipcRenderer.invoke('call:stop'),
  pauseCall: (paused) => ipcRenderer.invoke('call:pause', paused),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  setNotepad: (text) => ipcRenderer.invoke('notepad:set', text),
  openLibrary: () => ipcRenderer.invoke('library:open'),
  listCalls: (query) => ipcRenderer.invoke('calls:list', query),
  getCall: (id) => ipcRenderer.invoke('calls:get', id),
  noteTemplates: () => ipcRenderer.invoke('calls:templates'),
  writeNotes: (id, template) => ipcRenderer.invoke('calls:notes', id, template),
  askCalls: (question) => ipcRenderer.invoke('calls:ask', question),
  cancelAsk: () => ipcRenderer.invoke('calls:ask-cancel'),
  saveCallNotepad: (id, text) => ipcRenderer.invoke('calls:notepad', id, text),
  copyCallNotes: (id) => ipcRenderer.invoke('calls:copy', id),
  revealCall: (id) => ipcRenderer.invoke('calls:reveal', id),
  deleteCall: (id) => ipcRenderer.invoke('calls:delete', id),
  connectorStatus: () => ipcRenderer.invoke('connector:status'),
  connectClaudeCode: () => ipcRenderer.invoke('connector:connect'),
  disconnectClaudeCode: () => ipcRenderer.invoke('connector:disconnect'),
  addToClaudeDesktop: () => ipcRenderer.invoke('connector:desktop'),
  setupClaude: () => ipcRenderer.invoke('setup:claude'),
  setupAudio: () => ipcRenderer.invoke('setup:audio'),
  setupFinish: () => ipcRenderer.invoke('setup:finish'),
  setupPrivacy: (which) => ipcRenderer.invoke('setup:privacy', which),
  report: () => ipcRenderer.invoke('report:get'),
  openReport: () => ipcRenderer.invoke('report:open'),
  revealLog: () => ipcRenderer.invoke('report:reveal'),
  ask: (text, kind) => ipcRenderer.invoke('qa:ask', { text, kind }),
  cancel: (id) => ipcRenderer.invoke('qa:cancel', id),
  downloadModel: (id) => ipcRenderer.invoke('model:download', id),
  cancelDownload: () => ipcRenderer.invoke('model:cancel'),
  ensureMicAccess: () => ipcRenderer.invoke('mic:ensure-access'),
  micPcm: (buffer) => ipcRenderer.send('mic:pcm', buffer),
  micState: (state) => ipcRenderer.send('mic:state', state),
  pickFiles: () => ipcRenderer.invoke('dialog:files'),
  pickFolder: (title, defaultPath) => ipcRenderer.invoke('dialog:folder', title, defaultPath),
  copy: (text) => ipcRenderer.invoke('clipboard:write', text),
  open: (what) => ipcRenderer.invoke('shell:open', what),
  on: (channel, fn) => {
    if (!CHANNELS.has(channel)) throw new Error(`Unknown channel ${channel}`);
    const handler = (_e, ...args) => fn(...args);
    ipcRenderer.on(channel, handler);
    return () => ipcRenderer.removeListener(channel, handler);
  },
});
